"""Generate src/pyunicode.rs from this CPython's Unicode data.

The tables let the native tools reproduce the str predicates and the re classes
the original Python builder relied on, so they must come from the same CPython.
Run from the repository root, then format:

    python tools/ozzit/gen_pyunicode.py > tools/ozzit/src/pyunicode.rs
    cargo fmt --manifest-path tools/ozzit/Cargo.toml
"""

import re
import string
import sys
import unicodedata
from collections.abc import Callable

if (
    sys.implementation.name != "cpython"
    or sys.version_info[:3] != (3, 15, 0)
    or unicodedata.unidata_version != "17.0.0"
):
    raise SystemExit("Use CPython 3.15.0 with Unicode 17.0.0, which the tables reproduce")


def ranges(pred: Callable[[str], bool]) -> list[tuple[int, int]]:
    out: list[tuple[int, int]] = []
    start: int | None = None
    for cp in range(0x110000):
        ok = pred(chr(cp))
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def fmt_ranges(name: str, rs: list[tuple[int, int]]) -> str:
    body = "\n".join(f"    (0x{a:04X}, 0x{b:04X})," for a, b in rs)
    return f"pub static {name}: &[(u32, u32)] = &[\n{body}\n];\n"


def mapping(name: str, fn: Callable[[str], str]) -> str:
    rows = []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        c = chr(cp)
        f = fn(c)
        if f != c:
            esc = "".join("\\u{%X}" % ord(x) for x in f)
            rows.append(f'    (0x{cp:04X}, "{esc}"),')
    return f"pub static {name}: &[(u32, &str)] = &[\n" + "\n".join(rows) + "\n];\n"


# The non-ASCII characters an ASCII letter matches under re.IGNORECASE.
extra = []
for letter in string.ascii_lowercase:
    pattern = re.compile(letter, re.IGNORECASE)
    cps = [cp for cp in range(0x80, 0x110000) if pattern.fullmatch(chr(cp))]
    if cps:
        extra.append(f"('{letter}', &[{', '.join(f'0x{cp:04X}' for cp in cps)}])")

zero = [cp for cp in range(0x110000) if chr(cp).isdecimal() and unicodedata.decimal(chr(cp)) == 0]

out = [
    "// Generated by gen_pyunicode.py from CPython "
    f"{sys.version.split()[0]} (Unicode {unicodedata.unidata_version}). Do not edit.",
    "// Tables reproduce the str predicates and mappings the original Python builder used.",
    "",
    fmt_ranges("NOT_PRINTABLE", ranges(lambda c: not c.isprintable())),
    fmt_ranges("SPACE", ranges(str.isspace)),
    fmt_ranges("DECIMAL", ranges(str.isdecimal)),
    fmt_ranges("WORD", ranges(lambda c: re.fullmatch(r"\w", c) is not None)),
    mapping("CASEFOLD", str.casefold),
    f"pub static IGNORECASE_EXTRA: &[(char, &[u32])] = &[{', '.join(extra)}];\n",
    "pub static DECIMAL_ZERO: &[u32] = &[\n" + "\n".join(f"    0x{c:04X}," for c in zero) + "\n];\n",
]
sys.stdout.buffer.write("\n".join(out).encode("utf-8"))
