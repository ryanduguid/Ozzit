//! Join the six source texts into the single published AFE module.
use crate::{common::*, compiler, formula, py};
use std::{
    collections::{BTreeMap, BTreeSet},
    path::Path,
};

const BANNER: &str = "/*  Ozzit: every module of src/ joined as one Advanced Formula Environment module.\n    Generated by tools/build_module.py; edit src/ and rebuild, never this file.\n    Import it as a new module named oz to recreate the shipped oz. names. */\n\n";
const USAGE: &str = "usage: ozzit build_module [-h] [--check] [src] [output] [workbook] [index]";

pub fn build(src: &Path) -> Result<String> {
    let mut out = BANNER.to_owned();
    for module in formula::MODULES {
        let mut text = read_text(&src.join(format!("{module}.txt")))?;
        if !text.ends_with('\n') {
            text.push('\n');
        }
        out.push_str(&format!("/*  ===== {module} ===== */\n{text}\n"));
    }
    Ok(out)
}

pub fn declared_names(text: &str) -> Vec<String> {
    formula::statements(text)
        .iter()
        .flat_map(|s| captures(formula::NAME, s))
        .map(|m| m[1].clone())
        .collect()
}

/// Problems visible in the module text alone.
fn text_failures(text: &str, declared: &[String], failures: &mut BTreeSet<String>) {
    if text.contains('\r') {
        failures.insert("module text contains a carriage return".into());
    }
    if !text.ends_with('\n') {
        failures.insert("module text does not end with a newline".into());
    }
    if text.contains("oz.oz.") {
        failures.insert("module text contains a doubled oz. prefix".into());
    }
    for statement in formula::statements(text) {
        if !py::strip(&statement).is_empty() && !matches(formula::NAME, &statement) {
            failures.insert(format!(
                "statement is not a declaration: {}",
                py::repr_str(prefix(py::strip(&statement), 60))
            ));
        }
    }
    let mut counts = BTreeMap::new();
    for name in declared {
        *counts.entry(name).or_insert(0) += 1;
    }
    let mut folded = BTreeMap::new();
    for name in declared {
        let earlier = folded.entry(py::casefold(name)).or_insert(name);
        if *earlier != name || counts[name] > 1 {
            failures.insert(format!(
                "{name} is declared more than once (case-insensitively)"
            ));
        }
    }
}

pub fn check(text: &str, workbook: &Path, index: &Path) -> Result<Vec<String>> {
    let mut failures = BTreeSet::new();
    let declared = declared_names(text);
    text_failures(text, &declared, &mut failures);
    let shipped = compiler::workbook_names(workbook)?
        .into_iter()
        .map(|s| s[3..].to_owned())
        .collect::<BTreeSet<_>>();
    let csv = Csv::read(index)?;
    if csv
        .headers
        .iter()
        .filter(|h| h.as_str() == "function")
        .count()
        > 1
    {
        failures.insert(format!(
            "{}: duplicate CSV column(s): function",
            basename(index)
        ));
        return Ok(failures.into_iter().collect());
    }
    let mut indexed = BTreeSet::new();
    for row in &csv.rows {
        let name = csv.get(row, "function").unwrap_or("");
        if let Some(bare) = name.strip_prefix("oz.") {
            indexed.insert(bare.to_owned());
        } else {
            failures.insert(format!(
                "{}: invalid function name {}; expected oz. prefix",
                basename(index),
                py::repr_str(name)
            ));
        }
    }
    let declared = declared.into_iter().collect::<BTreeSet<_>>();
    for (label, expected) in [("workbook", shipped), ("functions.csv", indexed)] {
        for name in expected.difference(&declared) {
            failures.insert(format!(
                "{label} ships oz.{name}, which the module text does not declare"
            ));
        }
        for name in declared.difference(&expected) {
            failures.insert(format!(
                "module text declares {name}, which the {label} does not ship"
            ));
        }
    }
    Ok(failures.into_iter().collect())
}

/// The positional arguments and `--check`, or the help or usage error to print.
fn parse_args(args: &[String]) -> std::result::Result<(Vec<&str>, bool), Output> {
    let mut positional = Vec::new();
    let mut check_only = false;
    let mut end_options = false;
    let mut unknown = Vec::new();
    for arg in args {
        if !end_options && arg == "--" {
            end_options = true;
        } else if !end_options && arg == "--check" {
            check_only = true;
        } else if !end_options && matches!(arg.as_str(), "-h" | "--help") {
            return Err(Output::ok(vec![format!(
                "{USAGE}\n\nPublish src/ as one Advanced Formula Environment module.\n\npositional arguments:\n  src         source directory (default: src)\n  output      output module (default: oz.txt)\n  workbook    authoritative workbook (default: ozzit.xlsx)\n  index       function index (default: functions.csv)\n\noptions:\n  -h, --help  show this help message and exit\n  --check     check the output without writing (default: False)"
            )]));
        } else if !end_options
            && arg.starts_with('-')
            && !matches(r"^-\d+$|^-\d*\.\d+$", arg)
            && arg != "-"
        {
            unknown.push(arg.as_str());
        } else {
            positional.push(arg.as_str());
        }
    }
    unknown.extend(positional.iter().skip(4).copied());
    if !unknown.is_empty() {
        return Err(Output {
            code: 2,
            out: vec![],
            err: vec![
                USAGE.into(),
                format!(
                    "ozzit build_module: error: unrecognized arguments: {}",
                    unknown.join(" ")
                ),
            ],
        });
    }
    Ok((positional, check_only))
}

fn publish(text: &str, output: &Path, check_only: bool, names: usize) -> Output {
    if check_only {
        let current = if output.is_file() {
            match read_bytes(output) {
                Ok(bytes) => bytes,
                Err(e) => return Output::stderr(e),
            }
        } else {
            vec![]
        };
        if current != text.as_bytes() {
            return Output::failure(format!(
                "FAIL: {} is stale; run ozzit build_module",
                display(output)
            ));
        }
        Output::ok(vec![format!(
            "OK: {} is current, {names} names",
            display(output)
        )])
    } else {
        if let Err(e) = write_bytes(output, text.as_bytes()) {
            return Output::stderr(e);
        }
        Output::ok(vec![format!(
            "wrote {}: {names} names, {} bytes",
            display(output),
            text.len()
        )])
    }
}

pub fn command(args: &[String]) -> Output {
    let (positional, check_only) = match parse_args(args) {
        Ok(parsed) => parsed,
        Err(refusal) => return refusal,
    };
    let src = Path::new(positional.first().copied().unwrap_or("src"));
    let output = Path::new(positional.get(1).copied().unwrap_or("oz.txt"));
    let workbook = Path::new(positional.get(2).copied().unwrap_or("ozzit.xlsx"));
    let index = Path::new(positional.get(3).copied().unwrap_or("functions.csv"));
    let text = match build(src) {
        Ok(text) => text,
        Err(e) => return Output::stderr(e),
    };
    let failures = match check(&text, workbook, index) {
        Ok(failures) => failures,
        Err(e) => return Output::stderr(e),
    };
    if !failures.is_empty() {
        return Output {
            code: 1,
            out: failures.into_iter().map(|f| format!("FAIL: {f}")).collect(),
            err: vec![],
        };
    }
    let names = declared_names(&text).len();
    publish(&text, output, check_only, names)
}
